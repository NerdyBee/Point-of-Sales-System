/**
 * Licence tool for the vendor (you). Keep the private key OFF the shop's devices and out of git.
 *
 *   npm run license -- keygen                       create the signing key (once) and update src/license/publicKey.ts
 *   npm run license -- issue --device ABCD-EFGH-JKLM --name "Mama Nkechi Stores" [--days 365 | --expires 2027-12-31]
 *   npm run license -- verify --device ABCD-EFGH-JKLM --code <activation code>
 *   npm run license -- reset-pin --request ABCD-EFGH-JKLM-WXYZ-2345   one-time code for a forgotten owner PIN
 *   npm run license -- open-backup --file <backup.json> --password <new>   unlock a backup whose password was lost
 *
 * The private key lives in mobile/.license/private-key.json (git-ignored). Back it up: without
 * it you cannot issue codes for apps already built with its public key.
 */
import { randomBytes, randomUUID } from "node:crypto";
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { lockBackup, newPasswordKey, unlockWithVendorKey, type LockedPayload } from "../src/standalone/backupCrypto";
import { issueLicense, issuePinReset, normalizeDeviceCode, parsePinResetRequest, pinResetRequestCode, publicKeyFor, verifyLicense, type LicensePayload } from "../src/license/license";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const keyDir = join(root, ".license");
const keyFile = join(keyDir, "private-key.json");
const issuedLog = join(keyDir, "issued.csv");
const resetLog = join(keyDir, "pin-resets.csv");
const publicKeyModule = join(root, "src", "license", "publicKey.ts");

function option(name: string) {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
}

function loadSecret() {
  if (!existsSync(keyFile)) throw new Error(`No signing key at ${keyFile}. Run: npm run license -- keygen`);
  return (JSON.parse(readFileSync(keyFile, "utf8")) as { secretKey: string }).secretKey;
}

function writePublicKey(publicKeyHex: string) {
  writeFileSync(
    publicKeyModule,
    `/** Public half of the vendor's licence signing key (generated by \`npm run license -- keygen\`). */\nexport const LICENSE_PUBLIC_KEY = "${publicKeyHex}";\n`
  );
}

// Show mistakes as a plain message, not a stack trace.
process.on("uncaughtException", (error) => {
  console.error(`\n${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
});

const command = process.argv[2];

if (command === "keygen") {
  if (existsSync(keyFile) && !process.argv.includes("--force")) {
    console.log(`A signing key already exists at ${keyFile}.\nReplacing it invalidates every activation code already issued (use --force only if you mean it).`);
    writePublicKey(publicKeyFor(loadSecret()));
    console.log("src/license/publicKey.ts refreshed from the existing key.");
    process.exit(0);
  }
  mkdirSync(keyDir, { recursive: true });
  const secretKey = randomBytes(32).toString("hex");
  writeFileSync(keyFile, JSON.stringify({ secretKey, createdAt: new Date().toISOString() }, null, 2), { mode: 0o600 });
  writePublicKey(publicKeyFor(secretKey));
  console.log(`Signing key created: ${keyFile}\nBACK THIS FILE UP somewhere safe and private. Then rebuild the app so it contains the new public key.`);
} else if (command === "issue") {
  const device = option("device");
  const name = option("name");
  if (!device || !name) {
    throw new Error(
      `${!device ? "Missing --device." : "Missing --name (the shop or customer the licence is for)."}\n\n` +
        'Example:\n  npm run license -- issue --device "3CUN-B7EN-MAWB" --name "Mama Nkechi Stores" --days 365\n\n' +
        "  --days 365 or --expires 2027-12-31 sets an expiry; leave both out for a licence that never expires."
    );
  }
  if (!/^[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}$/.test(normalizeDeviceCode(device))) {
    throw new Error(`"${device}" is not a device code. It looks like ABCD-EFGH-JKLM (12 letters/digits); put it in quotes if it has spaces.`);
  }
  const days = option("days");
  const expires = option("expires") ?? (days ? new Date(Date.now() + Number(days) * 86_400_000).toISOString().slice(0, 10) : null);
  if (expires && !/^\d{4}-\d{2}-\d{2}$/.test(expires)) throw new Error("--expires must look like 2027-12-31");
  const payload: LicensePayload = {
    v: 1,
    id: `LIC-${randomUUID().slice(0, 8).toUpperCase()}`,
    name: name.trim(),
    device: normalizeDeviceCode(device),
    issued: new Date().toISOString().slice(0, 10),
    expires
  };
  const code = issueLicense(loadSecret(), payload);
  mkdirSync(keyDir, { recursive: true });
  if (!existsSync(issuedLog)) appendFileSync(issuedLog, "licence id,shop,device,issued,expires\n");
  appendFileSync(issuedLog, `${payload.id},"${payload.name.replace(/"/g, '""')}",${payload.device},${payload.issued},${payload.expires ?? "never"}\n`);
  console.log(`Licence ${payload.id} for "${payload.name}" on device ${payload.device}${expires ? `, valid until ${expires}` : ", no expiry"}.\n\nSend this activation code to the shop (copy it exactly):\n\n${code}\n`);
} else if (command === "verify") {
  const device = option("device");
  const code = option("code");
  if (!device || !code) throw new Error("Usage: verify --device ABCD-EFGH-JKLM --code <activation code>");
  const result = verifyLicense(code, { publicKeyHex: publicKeyFor(loadSecret()), deviceCode: device });
  console.log(result.ok ? `Valid: ${JSON.stringify(result.license)}` : `Invalid (${result.reason}): ${result.message}`);
} else if (command === "reset-pin") {
  const request = option("request");
  if (!request) {
    throw new Error(
      "Missing --request (the request code shown on the shop's phone under Forgot PIN?).\n\n" +
        'Example:\n  npm run license -- reset-pin --request "3CUN-B7EN-MAWB-7KQ2-X9TD"'
    );
  }
  const parsed = parsePinResetRequest(request);
  if (!parsed) throw new Error(`"${request}" is not a request code. It looks like ABCD-EFGH-JKLM-WXYZ-2345 (20 letters/digits).`);
  // Who is this device licensed to? Check it matches the person asking before sending the code.
  const licensedTo = existsSync(issuedLog)
    ? readFileSync(issuedLog, "utf8")
        .split(/\r?\n/)
        .filter((line) => line.includes(`,${parsed.device},`))
        .map((line) => line.split(",").slice(1, -3).join(",").replace(/^"|"$/g, "").replace(/""/g, '"'))
    : [];
  const id = `PIN-${randomUUID().slice(0, 8).toUpperCase()}`;
  const code = issuePinReset(loadSecret(), { v: 1, kind: "pin_reset", id, device: parsed.device, nonce: parsed.nonce, issued: new Date().toISOString().slice(0, 10) });
  mkdirSync(keyDir, { recursive: true });
  if (!existsSync(resetLog)) appendFileSync(resetLog, "reset id,device,request,issued at\n");
  appendFileSync(resetLog, `${id},${parsed.device},${pinResetRequestCode(parsed.device, parsed.nonce)},${new Date().toISOString()}\n`);
  console.log(
    `Device ${parsed.device} is licensed to: ${licensedTo.length ? [...new Set(licensedTo)].join(" / ") : "(not in your issued.csv - check who is asking!)"}\n` +
      "Only send this code if you are sure the request comes from that shop's owner.\n\n" +
      `Reset ${id}. Send this reset code (copy it exactly). It works once, on that phone only:\n\n${code}\n`
  );
} else if (command === "open-backup") {
  const file = option("file");
  const password = option("password");
  if (!file) {
    throw new Error(
      "Missing --file (the backup file the shop sent you).\n\n" +
        'Example:\n  npm run license -- open-backup --file "C:\\Users\\DELL\\Downloads\\ajokepos-mama-nkechi-2026-10-13.json" --password "NewPass123"\n\n' +
        "  --password  re-locks the backup with a new password for the owner (recommended).\n" +
        "  --unlocked  instead writes an unlocked copy (contains customer details and PIN hashes: handle with care)."
    );
  }
  if (!password && !process.argv.includes("--unlocked")) throw new Error("Add --password <new password for the owner> (or --unlocked for an unprotected copy).");
  if (password && password.length < 6) throw new Error("The new password needs at least 6 characters.");
  const backup = JSON.parse(readFileSync(file, "utf8")) as { format?: string; version?: number; locked?: LockedPayload } & Record<string, unknown>;
  if (backup.format !== "naijapos-tablet-backup") throw new Error("That file is not an Ajoke POS backup.");
  if (backup.version !== 2 || !backup.locked) throw new Error("That backup is not locked; the shop can restore it as it is.");
  const contents = unlockWithVendorKey(backup.locked, loadSecret());
  const random = (length: number) => new Uint8Array(randomBytes(length));
  const outFile = file.replace(/\.json$/i, "") + (password ? "-new-password.json" : "-UNLOCKED.json");
  if (password) {
    void newPasswordKey(password, random).then((passwordKey) => {
      const locked = lockBackup(contents, { passwordKey, vendorPublicKeyHex: publicKeyFor(loadSecret()), random });
      writeFileSync(outFile, JSON.stringify({ ...backup, locked }));
      console.log(`Backup re-locked with the new password.\n\nSend this file to the shop:\n  ${outFile}\n\nThey restore it with the password "${password}" (Backup → Restore from backup file). Ask them to change it afterwards under Backup → Change backup password.\n`);
    });
  } else {
    writeFileSync(outFile, JSON.stringify({ format: backup.format, version: 1, exportedAt: backup.exportedAt, tenantId: backup.tenantId, businessName: backup.businessName, ...JSON.parse(contents) }));
    console.log(`Unlocked copy written to:\n  ${outFile}\n\nIt is NOT protected: it holds customer details and staff PIN hashes. Delete it once the shop has restored it.\n`);
  }
} else {
  console.log("Commands: keygen | issue --device <code> --name <shop> [--days N | --expires YYYY-MM-DD] | verify --device <code> --code <code> | reset-pin --request <request code> | open-backup --file <backup> --password <new>");
}
